import { loadTerm } from './loadTerms'

type Registration = { assignmentKey?: string; blockSection: string; status: string; students?: { Email?: string; StudentID?: string }[] }
type Enrollment = { course_id: string; block_section?: string | null; student_email: string; suspended?: boolean | null }
/** Students of each block of an instructor course: the confirmed class list, and enrollments once the course exists. */
export function classStudents(course: { assignmentKey?: string; blocks: string[]; courseIds: string[] }, registrations: Registration[] = [], enrollments: Enrollment[] = []) {
  const result = new Map<string, Set<string>>(course.blocks.map(block => [block, new Set<string>()]))
  for (const row of registrations) if (row.status === 'active' && row.assignmentKey === course.assignmentKey && result.has(row.blockSection)) for (const student of row.students || []) { const id = (student.Email || student.StudentID || '').toLowerCase(); if (id) result.get(row.blockSection)!.add(id) }
  for (const row of enrollments) if (!row.suspended && course.courseIds.includes(row.course_id) && result.has(row.block_section || '')) result.get(row.block_section || '')!.add(row.student_email.toLowerCase())
  return result
}
