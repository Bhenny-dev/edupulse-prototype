const TONES = ['sky', 'purple', 'green', 'amber'] as const
/** A stable card colour per course code, so a class keeps its colour on Home and in its banner. */
export function classTone(code: string) {
  let hash = 0
  for (const character of code.replace(/\s/g, '').toUpperCase()) hash = (hash * 31 + character.charCodeAt(0)) >>> 0
  return TONES[hash % TONES.length]
}

/** Class codes: 7 letters or numbers without I, L, O, 0 or 1 (generated by the database). */
export const CLASS_CODE = /^[A-HJKMNP-Z2-9]{7}$/
export const normalizeClassCode = (raw: string) => String(raw || '').replace(/[^A-Za-z0-9]/g, '').toUpperCase()
export const isClassCode = (raw: string) => CLASS_CODE.test(normalizeClassCode(raw))

export type LinkProvider = { id: string; label: string; open: string }
const PROVIDERS: (LinkProvider & { test: (url: URL) => boolean })[] = [
  { id: 'youtube', label: 'YouTube', open: 'Watch on YouTube', test: url => /(^|\.)(youtube\.com|youtube-nocookie\.com|youtu\.be)$/.test(url.hostname) },
  { id: 'google-docs', label: 'Google Docs', open: 'Open in Google Docs', test: url => url.hostname === 'docs.google.com' && url.pathname.startsWith('/document/') },
  { id: 'google-slides', label: 'Google Slides', open: 'Open in Google Slides', test: url => url.hostname === 'docs.google.com' && url.pathname.startsWith('/presentation/') },
  { id: 'google-sheets', label: 'Google Sheets', open: 'Open in Google Sheets', test: url => url.hostname === 'docs.google.com' && url.pathname.startsWith('/spreadsheets/') },
  { id: 'google-forms', label: 'Google Forms', open: 'Open in Google Forms', test: url => (url.hostname === 'docs.google.com' && url.pathname.startsWith('/forms/')) || url.hostname === 'forms.gle' },
  { id: 'google-drawings', label: 'Google Drawings', open: 'Open in Google Drawings', test: url => url.hostname === 'docs.google.com' && url.pathname.startsWith('/drawings/') },
  { id: 'google-drive', label: 'Google Drive', open: 'Open in Google Drive', test: url => url.hostname === 'drive.google.com' },
]
const WEB: LinkProvider = { id: 'link', label: 'Link', open: 'Open link' }

/** Reads a pasted link. Only complete http(s) links are accepted; the resource stays with its provider. */
export function parseLink(raw: string): { url: string; provider: LinkProvider } {
  let url: URL
  try { url = new URL(String(raw || '').trim()) } catch { throw new Error('Paste a complete link that starts with https://') }
  if (!['https:', 'http:'].includes(url.protocol) || !url.hostname.includes('.')) throw new Error('Paste a complete link that starts with https://')
  if (url.href.length > 2000) throw new Error('Use a link of up to 2,000 characters.')
  return { url: url.href, provider: PROVIDERS.find(item => item.test(url)) || WEB }
}
export function linkProvider(raw: string): LinkProvider {
  try { return parseLink(raw).provider } catch { return WEB }
}
/** The video ID of a YouTube watch, short, embed or youtu.be link; anything else is not embedded. */
export function youtubeId(raw: string): string | null {
  let url: URL
  try { url = new URL(raw) } catch { return null }
  if (linkProvider(raw).id !== 'youtube') return null
  const candidate = url.hostname.endsWith('youtu.be') ? url.pathname.slice(1).split('/')[0] : url.searchParams.get('v') || url.pathname.match(/^\/(?:embed|shorts|live)\/([^/?#]+)/)?.[1] || ''
  return /^[A-Za-z0-9_-]{11}$/.test(candidate) ? candidate : null
}
export type LinkAttachment = { kind: 'link'; url: string; title: string; provider: string }
export const isLinkAttachment = (item: unknown): item is LinkAttachment => Boolean(item && typeof item === 'object' && (item as { kind?: string }).kind === 'link' && typeof (item as { url?: string }).url === 'string')
export function linkAttachment(raw: string, title = ''): LinkAttachment {
  const { url, provider } = parseLink(raw)
  return { kind: 'link', url, title: title.trim().slice(0, 200) || provider.label + (provider.id === 'link' ? `: ${new URL(url).hostname}` : ''), provider: provider.id }
}
