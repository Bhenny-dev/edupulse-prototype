 await modal.getByRole('button',{name:'Save delivery schedule'}).click()
 expect(fixture.commands).toEqual([])
 const pattern=page.getByRole('region',{name:'Weekly class pattern'})
 await pattern.getByLabel('Week 1 class date',{exact:true}).fill('2026-11-20')
 await pattern.getByLabel('Class start',{exact:true}).fill('07:30')
