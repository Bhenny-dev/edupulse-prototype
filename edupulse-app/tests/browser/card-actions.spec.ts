import {test,expect} from '@playwright/test'
import {deanManagementUI} from '../dean-management-fixture'

for(const role of ['dean','associate_dean']){
 test(`${role} course card menu creates, edits, suspends and removes with fresh records`,async({page},info)=>{
  const fixture=await deanManagementUI(page,role)
  await page.goto('/#/records')
  const more=page.getByRole('button',{name:'Course actions for IT 401',exact:true})
  await more.focus();await more.press('ArrowDown')
  const menu=page.getByRole('menu',{name:'Course actions for IT 401',exact:true})
  await expect(menu.getByRole('menuitem',{name:'Edit course'})).toBeFocused()
  await expect(menu.getByRole('menuitem',{name:'Remove course'})).toHaveCount(0)
  await page.reload();await expect(menu).toBeVisible()
  const box=await menu.boundingBox(),size=page.viewportSize()!
  expect(box!.y).toBeGreaterThanOrEqual(0);expect(box!.y+box!.height).toBeLessThanOrEqual(size.height)
  await page.keyboard.press('Escape');await expect(more).toBeFocused()
  expect(fixture.commands).toHaveLength(0)
  await page.getByRole('button',{name:'Add Course',exact:true}).click()
  const form=page.getByRole('dialog',{name:'Add Course',exact:true})
  await page.reload();await expect(form).toBeVisible();expect(fixture.commands).toHaveLength(0)
  await form.getByLabel('Course code',{exact:true}).fill('IT 999')
  await form.getByLabel('Course title',{exact:true}).fill('Applied computing')
  await form.getByLabel('Units',{exact:true}).fill('3')
  await form.getByRole('combobox',{name:'Year level',exact:true}).selectOption('3')
  await form.getByRole('button',{name:'Add Course',exact:true}).click()
  const card=page.locator('.dean-course-card').filter({has:page.getByRole('button',{name:'Course actions for IT 999',exact:true})})
  await expect(card).toContainText('Applied computing')
  expect(fixture.commands[0]).toMatchObject({action:'course.create',course:{code:'IT 999',title:'Applied computing',units:3,year:3}})
  await card.getByRole('button',{name:'Course actions for IT 999'}).click()
  await page.getByRole('menuitem',{name:'Edit course',exact:true}).click()
  const edit=page.getByRole('dialog',{name:'Edit Course',exact:true})
  await expect(edit.getByLabel('Course code',{exact:true})).toHaveAttribute('readonly','')
  await edit.getByLabel('Course title',{exact:true}).fill('Applied computing and design')
  await edit.getByRole('button',{name:'Save course'}).click()
  await expect(card).toContainText('Applied computing and design')
  await card.getByRole('button',{name:'Course actions for IT 999'}).click()
  await page.getByRole('menuitem',{name:'Suspend course',exact:true}).click()
  const suspend=page.getByRole('dialog',{name:'Suspend course',exact:true})
  await page.reload();await expect(suspend).toBeVisible();expect(fixture.commands).toHaveLength(2)
  await suspend.getByRole('button',{name:'Suspend course',exact:true}).click()
  await expect(card).toContainText('Suspended')
  await card.getByRole('button',{name:'Course actions for IT 999'}).click()
  const suspendedMenu=page.getByRole('menu',{name:'Course actions for IT 999'})
  await expect(suspendedMenu.getByRole('menuitem',{name:'Reactivate course'})).toBeVisible()
  await expect(suspendedMenu.getByRole('menuitem',{name:'Remove course'})).toBeVisible()
  await page.screenshot({path:`.data/card-actions/${role}-${info.project.name}-course-menu.png`,animations:'disabled'})
  await suspendedMenu.getByRole('menuitem',{name:'Remove course',exact:true}).click()
  await page.getByRole('dialog',{name:'Remove course',exact:true}).getByRole('button',{name:'Remove course',exact:true}).click()
  await expect(card).toHaveCount(0)
  expect(fixture.commands.map(c=>c.action)).toEqual(['course.create','course.update','course.status','course.status'])
 })
 test(`${role} instructor card actions use one menu and restore only the current action`,async({page},info)=>{
  const fixture=await deanManagementUI(page,role)
  await page.goto('/#/instructors')
  const card=page.locator('.dean-person-card').filter({hasText:'Alex Sample Instructor'})
  await expect(card.getByRole('button',{name:'Edit',exact:true})).toHaveCount(0)
  const more=card.getByRole('button',{name:'Instructor actions for Alex Sample Instructor',exact:true})
  await more.click()
  await expect(page.getByRole('menuitem',{name:'Remove instructor',exact:true})).toHaveCount(0)
  await page.getByRole('menuitem',{name:'Edit instructor',exact:true}).click()
  const edit=page.getByRole('dialog',{name:'Edit instructor',exact:true})
  await page.reload();await expect(edit).toBeVisible();expect(fixture.commands).toHaveLength(0)
  await edit.getByRole('button',{name:'Cancel',exact:true}).click()
  await more.click();await page.getByRole('menuitem',{name:'Suspend instructor',exact:true}).click()
  await page.getByRole('dialog',{name:'Suspend instructor',exact:true}).getByRole('button',{name:'Suspend',exact:true}).click()
  await expect(card).toContainText('Suspended')
  await more.click()
  await expect(page.getByRole('menuitem',{name:'Reactivate instructor',exact:true})).toBeVisible()
  await expect(page.getByRole('menuitem',{name:'Remove instructor',exact:true})).toBeVisible()
  await page.screenshot({path:`.data/card-actions/${role}-${info.project.name}-instructor-menu.png`,animations:'disabled'})
  await page.keyboard.press('Escape');await expect(more).toBeFocused()
  expect(fixture.commands).toEqual([{action:'account.status',id:'teacher-a',status:'suspended'}])
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 })
}
