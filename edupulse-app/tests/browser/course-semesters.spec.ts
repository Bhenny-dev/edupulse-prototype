import {test,expect} from '@playwright/test'
import {deanManagementUI} from '../dean-management-fixture'
import {instructorCourseUI} from '../instructor-course-fixture'

for(const role of ['dean','associate_dean'])test(`${role} uses one semester across pages and hides completed-semester actions`,async({page},info)=>{
 const fixture=await deanManagementUI(page,role)
 await page.goto('/#/records')
 await page.getByLabel('Academic term',{exact:true}).selectOption('2026-2027|2nd Semester')
 await page.getByRole('button',{name:'Add Course',exact:true}).click()
 const form=page.getByRole('dialog',{name:'Add Course',exact:true})
 await expect(form.getByRole('combobox')).toHaveCount(0)
 await form.getByLabel('Course code',{exact:true}).fill('QA NEXT')
 await form.getByLabel('Course title',{exact:true}).fill('Next-semester course')
 await form.getByLabel('Units',{exact:true}).fill('3')
 await page.screenshot({path:info.outputPath('three-course-fields.png'),animations:'disabled'})
 await form.getByRole('button',{name:'Add Course',exact:true}).click()
 await expect(page.locator('.data-table tbody tr')).toContainText(['Next-semester course'])
 expect(fixture.commands[0]).toEqual({action:'course.create',academic_year:'2026-2027',semester:'2nd Semester',course:{code:'QA NEXT',title:'Next-semester course',units:3}})
 await page.goto('/#/instructors')
 await expect(page.getByLabel('Academic term',{exact:true})).toHaveValue('2026-2027|2nd Semester')
 await page.getByLabel('Academic term',{exact:true}).selectOption('2025-2026|2nd Semester')
 await expect(page.getByRole('button',{name:'Add instructor',exact:true})).toHaveCount(0)
 await expect(page.getByRole('button',{name:/Instructor actions for/})).toHaveCount(0)
 await page.goto('/#/students')
 await expect(page.getByRole('button',{name:'Add student',exact:true})).toHaveCount(0)
 await expect(page.getByRole('button',{name:'Upload student list',exact:true})).toHaveCount(0)
 await page.goto('/#/records');await page.reload()
 await expect(page.getByLabel('Academic term',{exact:true})).toHaveValue('2025-2026|2nd Semester')
 await expect(page.getByRole('button',{name:'Add Course',exact:true})).toHaveCount(0)
 await expect(page.getByRole('button',{name:'Upload course load',exact:true})).toHaveCount(0)
 await expect(page.getByRole('button',{name:/Course actions for/})).toHaveCount(0)
 expect(fixture.commands).toHaveLength(1)
})

test('an assigned instructor confirms individual directory students in an existing block before a syllabus is uploaded',async({page},info)=>{
 const fixture=await instructorCourseUI(page),commands:Record<string,any>[]=[]
 const student={student_number:'DIR-42',full_name:'Cross Department Student',email:'directory@example.invalid',year_level:2,department:'College of Business Administration',program:'BSBA'}
 await page.route('**/api/ai?*',route=>new URL(route.request().url()).searchParams.get('action')==='students'?route.fulfill({json:{students:[student],total:1}}):route.fallback())
 await page.route('**/api/ai?action=academic',async route=>{
  if(route.request().method()!=='POST'||route.request().postDataJSON()?.operation!=='class-list')return route.fallback()
  const input=route.request().postDataJSON();commands.push(input)
  const parent=fixture.records.institutional!.find(r=>r.kind==='loads'&&r.record_key===input.assignment)!
  fixture.records.institutional!.push({kind:'loads',record_key:'confirmed-class',data:{...parent.data,Block:input.block,LoadType:'class',ParentLoadKey:input.assignment}})
  fixture.setWorkspace({...fixture.getWorkspace(),registrations:[{id:'confirmed',assignmentKey:input.assignment,academicYear:'2026-2027',semester:'1st Semester',courseCode:'IT 201',blockSection:input.block,status:'active',uploadedBy:parent.data.InstructorID,students:[{StudentID:student.student_number,Name:student.full_name,Email:student.email,YearLevel:'2'}]}]})
  return route.fulfill({json:{students:1,key:'confirmed-class'}})
 })
 await page.goto('/#/courseware')
 await page.locator('.instructor-course-card').filter({hasText:'IT 201'}).click()
 await page.getByRole('button',{name:'Class List',exact:true}).click()
 await page.getByRole('button',{name:'Add students',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'Course class list',exact:true})
 await expect(dialog.locator('input[type=file]')).toBeEnabled()
 await page.getByRole('button',{name:'Choose individual students',exact:true}).click()
 await dialog.getByRole('button',{name:'Choose students',exact:true}).click()
 await dialog.getByRole('checkbox',{name:'Select Cross Department Student'}).check()
 await expect(dialog.getByLabel('Block section',{exact:true})).toHaveValue('BSIT-2A')
 await expect(dialog.getByLabel('Block section',{exact:true})).toHaveAttribute('readonly','')
 await page.screenshot({path:info.outputPath('individual-directory-class.png'),animations:'disabled'})
 await dialog.getByRole('button',{name:'Register selected students (1)',exact:true}).click()
 await expect(dialog).toHaveCount(0)
 expect(commands).toHaveLength(1)
 expect(commands[0]).toMatchObject({operation:'class-list',block:'BSIT-2A',mode:'append',students:[{StudentID:'DIR-42',Email:'directory@example.invalid'}]})
 await page.getByRole('button',{name:'Block sections',exact:true}).click()
 await expect(page.locator('.instructor-block-card').filter({hasText:'BSIT-2A'})).toContainText('1 enrolled students')
 await page.getByRole('button',{name:'Block actions for BSIT-2A',exact:true}).click()
 await page.getByRole('menuitem',{name:'Manage class list',exact:true}).click()
 await page.reload();await expect(dialog).toBeVisible()
 expect(commands).toHaveLength(1)
})
