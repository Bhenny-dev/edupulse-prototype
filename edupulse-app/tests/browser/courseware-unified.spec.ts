test('one course list combines progress with View or Generate and preserves old links', async ({ page }) => {
  await unifiedCoursewareUI(page)
  await page.goto('/#/courseware?tab=mine')
  await expect(page.getByRole('button', { name: 'My Courseware', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Courseware Builder', exact: true })).toHaveCount(0)
  const started = page.locator('[data-course="baseline-syllabus"]'), empty = page.locator('[data-course="empty-course"]')
  await expect(started).toContainText('3 of 9 generated')
  await expect(started).toContainText('In Progress')
  await expect(started.getByRole('button', { name: 'View', exact: true })).toBeVisible()
  await expect(empty.getByRole('button', { name: 'Generate', exact: true })).toBeVisible()
  await empty.getByRole('button', { name: 'Generate', exact: true }).click()
  await expect(page).toHaveURL(/course=empty-course/)
  await expect(page.getByRole('button', { name: 'Generate All Content', exact: true })).toBeVisible()
  await page.goBack()
  await started.getByRole('button', { name: 'View', exact: true }).click()
  await page.locator('[data-week="1"]').getByRole('button', { name: 'View', exact: true }).click()
  await expect(page.locator('[data-content-id]')).toHaveCount(3)
  await expect(page.locator('[data-week="2"]').getByRole('button', { name: 'Generate', exact: true })).toBeVisible()
  await expect(page.locator('[data-week="9"]').getByRole('button')).toHaveCount(0)
  await page.goto('/#/courseware?tab=builder&course=baseline-syllabus&week=1')
  await expect(page.locator('[data-content-id]')).toHaveCount(3)
  await page.getByRole('button', { name: 'Back to courses', exact: true }).click()
  await expect(page.getByRole('table', { name: 'Courseware courses' })).toBeVisible()
})

