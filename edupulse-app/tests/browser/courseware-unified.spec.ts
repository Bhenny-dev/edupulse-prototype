test('missing-content generation preserves existing work and changes Generate into View', async ({ page }) => {
  const fixture = await unifiedCoursewareUI(page)
  const existing = JSON.stringify((fixture.getWorkspace() as { content: unknown }).content)
  const requested: {week:number;stepKey:string}[] = []
  await page.route('**/api/ai?action=courseware', async route => { const { week,stepKey } = route.request().postDataJSON(); requested.push({week,stepKey}); await route.fulfill({ json: generatedWeek(week) }) })
  await page.goto('/#/courseware?course=baseline-syllabus')
  await page.getByRole('button', { name: 'Course actions', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Generate missing content', exact: true }).click()
  await expect(page.locator('[data-content-id]')).toHaveCount(6)
  expect(requested).toEqual([2,3].flatMap(week=>['lesson-1','activity','assessment'].map(stepKey=>({week,stepKey}))))
  await expect(page.locator('[data-week="2"]').getByRole('button', { name: 'Generate', exact: true })).toHaveCount(0)
  await expect.poll(() => Object.keys((fixture.getWorkspace() as { content: object }).content).length).toBe(9)
  const saved = fixture.getWorkspace() as { content: Record<string, unknown> }
  for (const [id, item] of Object.entries(JSON.parse(existing))) expect(saved.content[id]).toEqual(item)
  await page.reload()
  await expect(page.locator('[data-week="2"]').getByRole('button', { name: 'View', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Back to courses', exact: true }).click()
  await expect(page.locator('[data-course="baseline-syllabus"]')).toContainText('9 of 9 generated')
  await expect(page.locator('[data-course="baseline-syllabus"]')).toContainText('In Progress')
})

test('week and course menus keep bulk review available', async ({ page }) => {
  const fixture = await unifiedCoursewareUI(page)
  await page.goto('/#/courseware?course=baseline-syllabus&week=1')
  await page.getByRole('button', { name: 'Week 1 actions', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Check All Drafts', exact: true }).click()
  await expect(page.locator('[data-content-id="unified-material"] .badge')).toHaveText('Checked')
  await page.getByRole('button', { name: 'Course actions', exact: true }).click()
  await expect(page.getByRole('menuitem', { name: 'Check All Drafts', exact: true })).toBeDisabled()
  await page.keyboard.press('Escape')
  // A fully reviewed week has no enabled menu action; Escape still dismisses it.
  await page.getByRole('button', { name: 'Week 1 actions', exact: true }).click()
  await expect(page.getByRole('menu')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('menu')).toHaveCount(0)
  await expect.poll(() => (fixture.getWorkspace() as { content: Record<string, { status: string }> }).content['unified-material'].status).toBe('checked')
  await page.reload()
  await expect(page.locator('[data-content-id="unified-material"] .badge')).toHaveText('Checked')
})

test('three-dot menus support keyboard, dismissal and a bounded viewport in dark mode', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('edupulse-dark-mode', 'true'))
  await unifiedCoursewareUI(page)
  await page.goto('/#/courseware')
  const trigger = page.getByRole('button', { name: 'More actions for IT 102', exact: true })
  await trigger.focus(); await page.keyboard.press('Enter')
  await expect(page.getByRole('menuitem', { name: 'View weekly outline' })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('menuitem', { name: 'Review drafts' })).toBeFocused()
  const rect = await page.getByRole('menu').boundingBox(), size = page.viewportSize()!
  expect(rect!.x).toBeGreaterThanOrEqual(0); expect(rect!.x + rect!.width).toBeLessThanOrEqual(size.width)
  expect(rect!.y + rect!.height).toBeLessThanOrEqual(size.height)
  await page.keyboard.press('Escape'); await expect(trigger).toBeFocused()
  await trigger.click(); await page.getByRole('heading', { name: 'Course', exact: true }).click()
  await expect(page.getByRole('menu')).toHaveCount(0)
  await trigger.click(); await page.getByRole('menuitem', { name: 'Review drafts', exact: true }).click()
  await expect(page.locator('[data-content-id="unified-material"]')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})

test('regenerating drafts preserves delivery dates, assessment rules and checked work', async ({ page }) => {
  const fixture = await unifiedCoursewareUI(page), workspace = unifiedWorkspace()
  const policy = { durationSeconds: 1200, maxAttempts: 2 }
  const checked = structuredClone(workspace.content['unified-activity'])
  fixture.setWorkspace({ ...workspace, content: { ...workspace.content,
    'unified-material': { ...workspace.content['unified-material'], releaseAt: '2026-12-01T00:00:00.000Z' },
    'baseline-quiz': { ...workspace.content['baseline-quiz'], status: 'draft', content: { ...workspace.content['baseline-quiz'].content, assessmentPolicy: policy } },
  } })
  await page.route('**/api/ai?action=courseware', route => route.fulfill({ json: generatedWeek(route.request().postDataJSON().week) }))
  await page.goto('/#/courseware?course=baseline-syllabus&week=1')
  await page.getByRole('button', { name: 'Week 1 actions', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Regenerate week', exact: true }).click()
  await expect(page.locator('[data-content-id="unified-material"]')).toContainText('Week 1 learning material')
  await expect.poll(() => (fixture.getWorkspace() as { content: Record<string, { title: string }> }).content['unified-material'].title).toBe('Week 1 learning material')
  const saved = (fixture.getWorkspace() as { content: Record<string, unknown> }).content
  expect(Object.keys(saved)).toHaveLength(3)
  expect(saved['unified-activity']).toEqual(checked)
  expect(saved['unified-material']).toHaveProperty('releaseAt', '2026-12-01T00:00:00.000Z')
  expect(saved['baseline-quiz']).toHaveProperty('content.assessmentPolicy', policy)
})
