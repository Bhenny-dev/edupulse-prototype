import { expect, test } from '@playwright/test'
import { deliveredAssessmentUI } from '../delivered-assessment-fixture'

test('a delivered assessment shows its form, verified key and the selected block scores in both instructor tabs', async ({ page }) => {
  const fixture = await deliveredAssessmentUI(page, 'instructor')
  fixture.failKey(true)
  await page.goto('/#/courseware?course=baseline-syllabus&tab=stream')
  await page.getByRole('button', { name: 'Open ' + fixture.check.title, exact: true }).click()
  const dialog = page.getByRole('dialog', { name: fixture.check.title, exact: true })
  await expect(dialog.getByRole('button', { name: 'Retry answer key' })).toBeVisible()
  fixture.failKey(false)
  await dialog.getByRole('button', { name: 'Retry answer key' }).click()
  await dialog.getByLabel('Question 1: total', { exact: true }).check()
  await dialog.getByLabel('Question 2: True', { exact: true }).check()
  await dialog.getByRole('textbox', { name: 'Written response for question 3' }).fill('Parameter')
  await dialog.getByRole('button', { name: 'Check my answers' }).click()
  await expect(dialog.getByRole('status')).toContainText('Test score: 1/2.')
  await expect(dialog.getByText('Your answer: True. Answer key: False.', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'Answer key', exact: true }).click()
  await expect(dialog.getByText('Accept parameter.', { exact: true })).toBeVisible()
  await expect(dialog.getByText('Correct answer: False', { exact: true })).toBeVisible()

  await dialog.getByRole('button', { name: 'Student scores', exact: true }).click()
  await expect(dialog.getByRole('row', { name: /Ada Reyes/ })).toContainText('0/5')
  await expect(dialog.getByRole('row', { name: /Ada Reyes/ })).toContainText('0%')
  await expect(dialog.getByRole('row', { name: /Bea Santos/ })).toContainText('Awaiting marking')
  await expect(dialog.getByRole('row', { name: /Bea Santos/ })).not.toContainText('2/5')
  await expect(dialog.getByRole('row', { name: /Cory Lim/ })).toContainText('No submission')
  await expect(dialog.getByRole('row', { name: /Drew Tan/ })).toContainText('Started')
  await expect(dialog.getByText('Evie Cruz')).toHaveCount(0)
  await dialog.getByRole('button', { name: 'Review responses for Bea Santos' }).click()
  let review = dialog.getByRole('region', { name: 'Responses for Bea Santos', exact: true })
  await expect(review.getByText('Student response: Parameter', { exact: true })).toBeVisible()
  await review.getByRole('combobox', { name: 'Question 3 points', exact: true }).selectOption('1')
  await review.getByRole('textbox', { name: 'Review reason' }).fill('This unsaved reason must clear.')
  await page.reload()
  review = dialog.getByRole('region', { name: 'Responses for Bea Santos', exact: true })
  await expect(review.getByRole('textbox', { name: 'Review reason' })).toHaveValue('', { timeout: 15000 })
  await expect(review.getByRole('combobox', { name: 'Question 3 points', exact: true })).toHaveValue('0')
  expect(fixture.commands.filter(command => command.operation !== 'instructor-assessment-key')).toEqual([])
  await review.getByRole('combobox', { name: 'Question 3 points', exact: true }).selectOption('1')
  await review.getByRole('textbox', { name: 'Review reason' }).fill('Correct identification.')
  await review.getByRole('button', { name: 'Confirm reviewed marks' }).click()
  await expect(dialog.getByRole('row', { name: /Bea Santos/ })).toContainText('3/5')
  expect(fixture.commands.filter(command => command.operation === 'grade')).toEqual([
    { operation: 'grade', attempt: 'aaaaaaaa-0000-4000-8000-000000000003', reason: 'Correct identification.', points: [1, 1, 1, 0, 0] },
  ])

  await dialog.getByRole('button', { name: 'Close delivered content' }).click()
  await page.getByRole('navigation', { name: 'Class sections' }).getByRole('button', { name: 'Teaching Materials & Assessments' }).click()
  const topic = page.locator('[data-topic="variables"]')
  await topic.locator('summary').click()
  await topic.locator('.instructor-sequence-item').filter({ hasText: fixture.check.title }).getByRole('button', { name: 'Open', exact: true }).click()
  await expect(dialog.getByRole('row', { name: /Bea Santos/ })).toContainText('3/5')
})

test('student forms submit the supported choice and written formats and show their own pending review', async ({ page }) => {
  const fixture = await deliveredAssessmentUI(page, 'student')
  page.on('dialog', prompt => prompt.accept())
  const submit = 'Confirm and submit responses'
  for (const [index, assessment] of [fixture.check, fixture.application].entries()) {
    await page.goto('/#/assessment')
    await page.getByRole('button', { name: 'Open assessment', exact: true }).nth(index).click()
    const dialog = page.getByRole('dialog', { name: assessment.title, exact: true })
    const first = dialog.getByRole('button', { name: 'Start assessment', exact: true })
    await expect(first).toBeEnabled()
    await expect(dialog.getByText(/Correct answer:/)).toHaveCount(0)
    await first.click()
    await expect(dialog.getByRole('button', { name: submit })).toBeDisabled()
    const textAnswer = (n: number) => dialog.getByRole('textbox', { name: 'Written response for question ' + n, exact: true })
    const expected = index === 0 ? fixture.answers : ['1-B\n2-A', '1. Read 5\n2. Add 2\n3. Confirm 7', 'Check the calculation independently.']
    if (index === 0) {
      await dialog.getByLabel('Question 1: total', { exact: true }).check()
      await dialog.getByLabel('Question 2: False', { exact: true }).check()
      await expect(textAnswer(3)).toHaveAttribute('type', 'text')
      await expect(dialog.getByText('Enter one item per line.', { exact: true })).toBeVisible()
      for (const n of [3, 4, 5]) await textAnswer(n).fill(String(expected[n - 1]))
    } else {
      await expect(dialog.getByRole('table')).toHaveCount(1)
      await expect(dialog.getByText('Enter the matching pairs', { exact: false })).toBeVisible()
      await expect(dialog.getByText('Describe your steps', { exact: false })).toBeVisible()
      for (const n of [1, 2, 3]) await textAnswer(n).fill(String(expected[n - 1]))
    }
    await dialog.getByRole('button', { name: submit }).click()
    await expect(dialog.getByRole('status').filter({ hasText: 'Score pending review' })).toBeVisible()
    const feedback = dialog.getByRole('group', { name: 'Answer review for attempt 1' })
    await expect(feedback.getByRole('listitem')).toHaveCount(expected.length)
    if (index === 0) await expect(feedback.getByText('Correct answer: False', { exact: true })).toBeVisible()
    await expect(feedback.getByText('Awaiting instructor review', { exact: true })).toHaveCount(3)
    expect(fixture.commands.findLast(command => command.operation === 'respond')?.responses).toEqual(expected)
    await page.reload()
    await expect(dialog.getByRole('status').filter({ hasText: 'Score pending review' })).toBeVisible({ timeout: 15000 })
  }
  expect(fixture.commands.filter(command => command.operation === 'respond')).toHaveLength(2)
  expect(fixture.commands.filter(command => command.operation === 'start')).toHaveLength(2)
  expect(fixture.commands.some(command => command.operation === 'instructor-assessment-key')).toBe(false)
})
