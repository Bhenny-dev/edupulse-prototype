import {test,expect} from '@playwright/test'
import {deanManagementUI} from '../dean-management-fixture'

for(const role of ['dean','associate_dean'])test(`${role} instructor details follow loads through assignment, removal and reload`,async({page},info)=>{
 await page.emulateMedia({reducedMotion:'reduce'})
 const fixture=await deanManagementUI(page,role)
 fixture.records.institutional=fixture.records.institutional!.filter(r=>r.kind!=='loads')
 const openTeacher=async()=>{
  await page.goto('/#/instructors')
  await page.getByRole('button',{name:'View instructor Alex Sample Instructor'}).click()
  return page.getByRole('dialog',{name:'Instructor Alex Sample Instructor'})
 }
 const empty=await openTeacher()
 await expect(empty.getByRole('cell',{name:'IT 102',exact:true})).toHaveCount(0)
 await expect(empty.getByRole('cell',{name:'IT 301',exact:true})).toHaveCount(0)
 await expect(empty).toContainText('No course load assigned for this term.')
 await page.reload()
 await expect(page.getByRole('dialog',{name:'Instructor Alex Sample Instructor'})).toBeVisible()
 await expect(empty.getByRole('cell',{name:'IT 102',exact:true})).toHaveCount(0)
 await empty.getByRole('heading',{name:'Syllabi and delivery',exact:true}).scrollIntoViewIfNeeded()
 await page.screenshot({path:`.data/instructor-handover/empty-${role}-${info.project.name}.png`,animations:'disabled'})
 expect(fixture.commands).toHaveLength(0)
 await empty.getByRole('button',{name:'Close',exact:true}).click()
 await page.goto('/#/records')
 await page.getByRole('button',{name:/^IT 102 Programming foundations,/}).click()
 let course=page.getByRole('dialog',{name:'IT 102 — Programming foundations'})
 await course.getByRole('button',{name:'Add instructor',exact:true}).click()
 const assign=page.getByRole('dialog',{name:'Load IT 102',exact:true})
 await assign.getByRole('combobox',{name:'Instructor',exact:true}).selectOption('teacher-a')
 await assign.locator('label.dean-chip',{hasText:'BSIT-1A'}).click()
 await assign.getByRole('button',{name:'Assign to 1 block'}).click()
 await expect(assign).toHaveCount(0)
 await course.getByRole('button',{name:'Close',exact:true}).click()
 const loaded=await openTeacher()
 await expect(loaded.getByRole('cell',{name:'IT 102',exact:true})).toHaveCount(2)
 await expect(loaded.getByRole('cell',{name:'IT 301',exact:true})).toHaveCount(0)
 await loaded.getByRole('button',{name:'Close',exact:true}).click()
 await page.goto('/#/records');await page.getByRole('button',{name:/^IT 102 Programming foundations,/}).click()
 course=page.getByRole('dialog',{name:'IT 102 — Programming foundations'})
 await course.getByRole('button',{name:'Remove Alex Sample Instructor from IT 102 BSIT-1A',exact:true}).click()
 const removal=page.getByRole('dialog',{name:'Remove course load'})
 await expect(removal).toContainText('retained for the replacement instructor')
 await removal.getByRole('button',{name:'Remove load',exact:true}).click()
 await expect(removal).toHaveCount(0)
 await course.getByRole('button',{name:'Close',exact:true}).click()
 const removed=await openTeacher()
 await expect(removed.getByRole('cell',{name:'IT 102',exact:true})).toHaveCount(0)
 await page.reload();await expect(removed).toContainText('No course load assigned for this term.')
 expect(fixture.commands).toHaveLength(2)
 expect(fixture.commands[1]).toMatchObject({action:'load.remove',expected_instructor:'teacher-a'})
})
