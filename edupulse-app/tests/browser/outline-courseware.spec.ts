import {test,expect} from '@playwright/test'
import {readFile} from 'node:fs/promises'
import {outlineCoursewareUI} from '../outline-courseware-fixture'

test('outline-driven generation saves two complete items, replaces an obsolete AI quiz and exports the full lesson',async({page})=>{
  test.setTimeout(90000)
  const fixture=await outlineCoursewareUI(page);await page.goto(`/#/courseware?course=${fixture.syllabus.id}&week=5`)
  await page.getByRole('button',{name:'Week 5 actions',exact:true}).click();await page.getByRole('menuitem',{name:'Regenerate week',exact:true}).click()
  await expect(page.getByText('Week 5: 2 AI drafts saved for review.',{exact:true})).toBeVisible()
  expect(fixture.requests.map(row=>row.key)).toEqual(['lesson-1','lesson-2','lesson-3','lesson-4','lesson-5','activity'])
  expect(fixture.prompts.filter(row=>row.generationStep.startsWith('lesson')).every(row=>row.topics.length===1)).toBeTruthy()
  await expect(page.locator('[data-content-id]')).toHaveCount(2)
  await expect(page.getByText('Previous automatic readiness quiz',{exact:true})).toHaveCount(0)
  await page.locator(`[data-content-id="${fixture.id}"]`).getByRole('button',{name:'View',exact:true}).click()
  await expect(page.getByText('Worked nested trace',{exact:true})).toBeVisible()
  const download=page.waitForEvent('download');await page.getByRole('button',{name:'Download PDF',exact:true}).click()
  const file=await (await download).path();expect(file).toBeTruthy();expect((await readFile(file!)).subarray(0,5).toString()).toBe('%PDF-')
  await page.reload();await expect(page.getByText('Previous automatic readiness quiz',{exact:true})).toHaveCount(0)
})
test('a failed part persists a private unfinished preview and resumes after reload without repeating saved calls',async({page})=>{
  const fixture=await outlineCoursewareUI(page);fixture.failStep('lesson-3');await page.goto(`/#/courseware?course=${fixture.syllabus.id}&week=5`)
  await page.getByRole('button',{name:'Week 5 actions',exact:true}).click();await page.getByRole('menuitem',{name:'Regenerate week',exact:true}).click()
  await expect(page.getByText('Generation did not finish',{exact:true})).toBeVisible()
  await expect(page.getByText('Previous short overview',{exact:true})).toBeVisible()
  await expect(page.getByText('Previous automatic readiness quiz',{exact:true})).toBeVisible()
  const checkpoint=page.locator('[data-content-id="generation-outline-plan-syllabus-w5"]')
  await expect(checkpoint.getByText('Unfinished',{exact:true})).toBeVisible()
  await expect(checkpoint.getByRole('checkbox')).toHaveCount(0)
  await checkpoint.getByRole('button',{name:'View',exact:true}).click()
  await expect(page.getByText('State, conditions and loop counters',{exact:true}).first()).toBeVisible()
  await expect(page.getByRole('button',{name:'Edit',exact:true})).toHaveCount(0)
  await page.getByRole('button',{name:'Back',exact:true}).click()
  expect(fixture.requests.map(row=>row.key)).toEqual(['lesson-1','lesson-2','lesson-3','lesson-4','lesson-5','activity'])
  expect((fixture.getWorkspace().content as any)['generation-outline-plan-syllabus-w5'].generationCheckpoint.results).toHaveLength(5)
  await page.reload()
  await expect(page.getByRole('button',{name:'Resume generation',exact:true})).toBeVisible()
  expect(fixture.requests).toHaveLength(6)
  fixture.failStep('')
  await page.getByRole('button',{name:'Resume',exact:true}).click()
  await expect(page.getByText('Week 5: 2 AI drafts saved for review.',{exact:true})).toBeVisible()
  expect(fixture.requests.map(row=>row.key)).toEqual(['lesson-1','lesson-2','lesson-3','lesson-4','lesson-5','activity','lesson-3'])
  await expect(checkpoint).toHaveCount(0)
  expect((fixture.getWorkspace().content as any)[fixture.id].content.sections[9].heading).toBe('Nested loops and independent practice')
  await expect(page.getByText('Previous automatic readiness quiz',{exact:true})).toHaveCount(0)
})

test('stopping between parts retains the last acknowledged draft and resumes only the outstanding parts',async({page})=>{
  const fixture=await outlineCoursewareUI(page);fixture.holdStep('lesson-2')
  await page.goto(`/#/courseware?course=${fixture.syllabus.id}&week=5`)
  await page.getByRole('button',{name:'Week 5 actions',exact:true}).click();await page.getByRole('menuitem',{name:'Regenerate week',exact:true}).click()
  await expect.poll(()=>fixture.requests.length).toBe(2)
  await expect(page.getByText('Week 5: unfinished draft (1/6 parts)',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Stop generation',exact:true}).click()
  await expect(page.getByRole('button',{name:'Resume',exact:true})).toBeEnabled()
  fixture.releaseStep()
  await page.getByRole('button',{name:'Resume',exact:true}).click()
  await expect(page.getByText('Week 5: 2 AI drafts saved for review.',{exact:true})).toBeVisible()
  expect(fixture.requests.map(row=>row.key)).toEqual(['lesson-1','lesson-2','lesson-2','lesson-3','lesson-4','lesson-5','activity'])
})

test('resume preserves edits made after an interrupted generation instead of adopting a new overwrite baseline',async({page})=>{
  const fixture=await outlineCoursewareUI(page);fixture.failStep('lesson-3')
  await page.goto(`/#/courseware?course=${fixture.syllabus.id}&week=5`)
  await page.getByRole('button',{name:'Week 5 actions',exact:true}).click();await page.getByRole('menuitem',{name:'Regenerate week',exact:true}).click()
  await expect(page.getByText('Generation did not finish',{exact:true})).toBeVisible()
  const workspace=structuredClone(fixture.getWorkspace()) as any
  workspace.content[fixture.id].content.title='Instructor revision after interruption'
  fixture.setWorkspace(workspace);await page.reload();fixture.failStep('')
  await page.getByRole('button',{name:'Resume',exact:true}).click()
  await expect(page.getByText(/A draft changed during generation/)).toBeVisible()
  expect((fixture.getWorkspace().content as any)[fixture.id].content.title).toBe('Instructor revision after interruption')
  expect(fixture.requests.filter(row=>row.key==='lesson-1')).toHaveLength(1)
})
