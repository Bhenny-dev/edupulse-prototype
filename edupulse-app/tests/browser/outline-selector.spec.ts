import {test,expect} from '@playwright/test'
import {componentBuilder} from '../pulse-component-fixture'
import {ASSESSMENT_FORMATS} from '../../src/data/assessmentFormats'

test('outline uses one contents field, seven assessment choices, multiple sections and shared week scope',async({page})=>{
 await page.emulateMedia({reducedMotion:'reduce'});await componentBuilder(page)
 const outline=page.getByRole('region',{name:'Course Outline editor',exact:true})
 await outline.getByRole('combobox',{name:'Outline week',exact:true}).selectOption('1');await outline.getByRole('button',{name:'Expand outline',exact:true}).focus();await page.keyboard.press('Enter')
 await expect(outline.getByRole('columnheader',{name:'Teaching-Learning Activities',exact:true})).toBeVisible()
 await expect(outline.getByRole('columnheader',{name:'Assessments',exact:true})).toBeVisible()
 await expect(outline.getByRole('button',{name:/teaching materials/i})).toHaveCount(0)
 await expect(outline.getByRole('button',{name:'Add Topic',exact:true})).toHaveCount(0)
 await page.getByLabel('Week 1 contents',{exact:true}).fill('Class orientation\nLesson 1: Introduction to multimedia')
 await page.getByLabel('Week 1 activities',{exact:true}).fill('Discussion and guided reading')
 const types=page.getByRole('combobox',{name:'Week 1 assessment types',exact:true})
 expect(await types.locator('option').allTextContents()).toEqual(['System chooses a suitable type',...ASSESSMENT_FORMATS.map(value=>value.label)])
 await types.selectOption({label:'Matching type'})
 await outline.getByRole('button',{name:'Add section to week 1',exact:true}).click()
 await expect(page.getByLabel('Week 1 section 1 contents',{exact:true})).toHaveValue('Class orientation\nLesson 1: Introduction to multimedia')
 await page.getByLabel('Week 1 section 2 contents',{exact:true}).fill('Multimedia formats')
 const share=outline.locator('.outline-section-controls').first();await share.getByText('Share section across weeks',{exact:true}).click()
 await share.getByLabel('Week 1 section 1 last shared week',{exact:true}).fill('2');await share.getByRole('button',{name:'Apply week range',exact:true}).click()
 await outline.getByRole('combobox',{name:'Outline week',exact:true}).selectOption('2')
 await expect(page.getByLabel('Week 2 contents',{exact:true})).toHaveValue('Class orientation\nLesson 1: Introduction to multimedia')
 await page.getByLabel('Week 2 contents',{exact:true}).fill('Shared orientation and multimedia')
 await outline.getByRole('combobox',{name:'Outline week',exact:true}).selectOption('1')
 await expect(page.getByLabel('Week 1 section 1 contents',{exact:true})).toHaveValue('Shared orientation and multimedia')
 await expect(page.getByLabel('Week 1 section 2 contents',{exact:true})).toHaveValue('Multimedia formats')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true)
})
