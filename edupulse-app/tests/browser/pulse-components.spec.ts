import { test, expect } from '@playwright/test'
import { componentBuilder, focusComponent, exampleFieldModel, fileTransfer } from '../pulse-component-fixture'
import { researchMethodsDraft } from '../syllabus-draft-fixture'

test('dragged field drafts only its own value, then confirmation saves and survives reload', async ({ page }, info) => {
  const field = await componentBuilder(page), requests = await exampleFieldModel(page)
  const pulse = await focusComponent(page, field, info.project.name === 'mobile')
  await pulse.getByRole('textbox', { name: 'Ask Pulse', exact: true }).fill('Draft this field using the selected course'); await pulse.getByRole('button', { name: 'Send', exact: true }).click()
  const card = pulse.getByRole('region', { name: 'Review content edit' })
  await expect(card).toContainText('Formulate a research question')
  await expect(card).not.toContainText('Unrelated replacement must not apply')
  await expect(field).toHaveValue('Original first outcome')
  expect(requests[0]?.section).toBe('programOutcomes')
  expect(requests[0]?.context).toContain('programOutcomes.0')
  await card.getByRole('button', { name: 'Confirm and save draft', exact: true }).click()
  await expect(pulse).toContainText('Draft saved.')
  const saved = (await (await page.request.get('/api/ai?action=workspace')).json()).data.syllabi.find((item: { programOutcomes?: string[] }) => item.programOutcomes?.[0]?.startsWith('Formulate a research question'))
  expect(saved.programOutcomes[1]).toBe('Keep this neighboring outcome')
  await page.reload({ waitUntil: 'domcontentloaded' })
  const after = (await (await page.request.get('/api/ai?action=workspace')).json()).data.syllabi.find((item: { id: string }) => item.id === saved.id)
  expect(after.programOutcomes).toEqual(saved.programOutcomes)
})

test('a changed form invalidates the field preview and an explicit whole-syllabus request broadens the scope', async ({ page }) => {
  const field = await componentBuilder(page); await exampleFieldModel(page)
  await field.focus(); await page.keyboard.press('Alt+p')
  const pulse = page.getByRole('dialog', { name: 'Pulse', exact: true })
  await pulse.getByRole('textbox', { name: 'Ask Pulse', exact: true }).fill('Improve this field'); await pulse.getByRole('button', { name: 'Send', exact: true }).click()
  const card = pulse.getByRole('region', { name: 'Review content edit' })
  await expect(card).toContainText('Formulate a research question')
  await field.fill('New manual wording')
  await card.getByRole('button', { name: 'Apply to open form', exact: true }).click()
  await expect(card.getByRole('alert')).toContainText('changed after this proposal')
  await expect(field).toHaveValue('New manual wording')
  await page.route('**/api/ai?action=operator', route => route.fulfill({ json: { patch: researchMethodsDraft, generated: true, requiresConfirmation: true } }))
  await pulse.getByRole('textbox', { name: 'Ask Pulse', exact: true }).fill('Generate all fields in this syllabus using research')
  await pulse.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(pulse.getByRole('region', { name: 'Review content edit' }).last().getByRole('checkbox')).toHaveCount(7)
})

test('files drop onto the closed mascot or chat without sending, while invalid batches preserve attachments', async ({ page }) => {
  await componentBuilder(page)
  const csv = await fileTransfer(page, [{ name: 'IT104-class-list.csv', type: 'text/csv', text: 'StudentID,Name,Email,Block\nSYN-1,Synthetic Learner,learner@example.invalid,BSIT-1A' }])
  await page.locator('[data-pulse-ui="mascot"]').dispatchEvent('drop', { dataTransfer: csv })
  const pulse = page.getByRole('dialog', { name: 'Pulse', exact: true })
  await expect(pulse.locator('.connected-pulse-attachments')).toContainText('1 students')
  const input = pulse.getByRole('textbox', { name: 'Ask Pulse', exact: true }); await input.fill('Keep my unsent question')
  const text = await fileTransfer(page, [{ name: 'research-notes.txt', text: 'Research questions guide the selection of methods and collection of relevant evidence.' }])
  await pulse.dispatchEvent('dragenter', { dataTransfer: text })
  await expect(pulse.getByText('Drop files to attach', { exact: true })).toBeVisible()
  await pulse.dispatchEvent('drop', { dataTransfer: text })
  await expect(pulse.locator('.connected-pulse-attachments')).toContainText('research-notes.txt')
  await expect(input).toHaveValue('Keep my unsent question')
  await expect(pulse.locator('.connected-pulse-message.from-user')).toHaveCount(0)
  const tooMany = await fileTransfer(page, [{ name: 'third.txt', text: 'Third file' }, { name: 'fourth.txt', text: 'Fourth file' }])
  await pulse.dispatchEvent('drop', { dataTransfer: tooMany })
  await expect(pulse.getByRole('alert')).toContainText('up to three files')
  await expect(pulse.locator('.connected-pulse-attachments li')).toHaveCount(2)
  const invalid = await fileTransfer(page, [{ name: 'unsupported.exe', text: 'Unsupported reference' }])
  await pulse.dispatchEvent('drop', { dataTransfer: invalid })
  await expect(pulse.getByRole('alert')).toBeVisible()
  await expect(pulse.locator('.connected-pulse-attachments li')).toHaveCount(2)
})


