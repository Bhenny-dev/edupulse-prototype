import { test, expect } from '@playwright/test'
import { componentBuilder } from '../pulse-component-fixture'

for (const role of ['System Admin', 'Dean', 'Assoc. Dean', 'Instructor', 'Student']) test(`${role} finds help and shortcuts in Settings with a clean top bar`, async ({ page }) => {
    await page.goto('/')
    await page.getByRole('button', { name: role, exact: true }).click()
    await page.goto('/#/settings?tab=help')
    await expect(page.getByRole('heading', { name: 'Help & Support', exact: true })).toBeVisible()
    await expect(page.getByRole('banner').getByTitle('Help & Support', { exact: true })).toHaveCount(0)
    await expect(page.getByRole('banner').getByTitle('Keyboard shortcuts (?)', { exact: true })).toHaveCount(0)
    const tabs = page.getByRole('navigation', { name: 'Settings sections' })
    await tabs.getByRole('button', { name: 'Keyboard Shortcuts', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Keyboard Shortcuts', exact: true })).toBeVisible()
    await expect(page.locator('.workspace-status')).toHaveCount(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.goto('/#/help')
  await expect(page).toHaveURL(/settings\?tab=help/)
  await page.getByRole('heading', { name: 'Settings', exact: true }).click()
  await page.keyboard.press('?')
  await expect(page).toHaveURL(/settings\?tab=keyboard-shortcuts/)
  await expect(page.getByRole('dialog', { name: 'Keyboard shortcuts', exact: true })).toHaveCount(0)
})

test('outline expands, filters weeks and swaps content without moving exam slots or losing resources', async ({ page }) => {
  await componentBuilder(page)
  const outline = page.getByRole('region', { name: 'Course Outline editor', exact: true })
  await expect(outline.locator('thead').first()).toBeVisible()
  expect(await outline.locator('tbody tr').first().evaluate(row => getComputedStyle(row).display)).toBe('table-row')
  await page.locator('[data-pulse-field="courseOutline.0.ilos"]').fill('Week one outcome')
  await page.locator('[data-pulse-field="courseOutline.1.ilos"]').fill('Week two outcome')
  await outline.getByRole('button', { name: 'Move week 1 later', exact: true }).click()
  await expect(page.locator('[data-pulse-field="courseOutline.0.ilos"]')).toHaveValue('Week two outcome')
  await expect(page.locator('[data-pulse-field="courseOutline.1.ilos"]')).toHaveValue('Week one outcome')
  await outline.getByRole('combobox', { name: 'Outline week', exact: true }).selectOption('2')
  await expect(outline.locator('textarea[placeholder="Learning outcome..."]')).toHaveCount(1)
  await expect(page.locator('[data-pulse-field="courseOutline.1.ilos"]')).toHaveValue('Week one outcome')
  const materials=outline.getByRole('button',{name:'Week 2 teaching materials',exact:true});await materials.focus();await page.keyboard.press('Enter');await expect(materials).toHaveAttribute('aria-expanded','true');await page.keyboard.press('Escape');await expect(materials).toHaveAttribute('aria-expanded','false')
  await outline.getByRole('button', { name: 'Expand outline', exact: true }).click()
  await expect(outline).toHaveClass(/is-expanded/)
  const rect = (await outline.boundingBox())!
  expect(rect.width).toBeGreaterThan((await page.viewportSize())!.width - 60)
  await page.keyboard.press('Escape')
  await expect(outline).not.toHaveClass(/is-expanded/)
  await outline.getByRole('combobox', { name: 'Outline week', exact: true }).selectOption('9')
  await expect(outline.getByText('Midterm Examination', { exact: true })).toBeVisible()
  await expect(outline.locator('textarea').first()).toBeDisabled()
  await outline.getByRole('combobox', { name: 'Outline term', exact: true }).selectOption('finals')
  await expect(outline.getByText('Final Examination', { exact: true })).toBeVisible()
  await expect(page.locator('[data-pulse-field="courseOutline.1.ilos"]')).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})

test('Pulse starts with conversation only and exposes optional tools on demand', async ({ page }) => {
  await componentBuilder(page)
  await page.getByRole('button', { name: 'Open Pulse assistant', exact: true }).click()
  const pulse = page.getByRole('dialog', { name: 'Pulse', exact: true })
  await expect(pulse).toContainText('What would you like help with?')
  await expect(pulse.locator('.connected-pulse-status, .pulse-office-entry, .connected-pulse-guide, .connected-pulse-footnote')).toHaveCount(0)
  await expect(pulse.getByRole('button', { name: 'Open workspace buddies', exact: true })).toHaveCount(0)
  await pulse.getByRole('button', { name: 'Pulse options', exact: true }).click()
  await expect(pulse.getByRole('button', { name: 'Open workspace buddies', exact: true })).toBeVisible()
  await pulse.getByRole('button', { name: 'Guide this page', exact: true }).click()
  await expect(pulse.getByRole('button', { name: 'Build a new syllabus', exact: true })).toBeVisible()
})
