for(const role of ['dean','associate_dean'])test(`${role} sees department home blocks before courses are assigned`,async({page},info)=>{
 const fixture=await deanManagementUI(page,role)
 fixture.records.courses=[];fixture.records.enrollments=[];fixture.records.publications=[];fixture.records.attempts=[];fixture.records.accesses=[]
 fixture.records.directory.students.push({id:'business-student',student_number:'2027-1-0099',name:'Business Student',surname:'Student',first_name:'Business',middle_name:'',email:'business@example.invalid',year_level:1,department:'Business',program:'Bachelor of Science in Accountancy',status:'active',block:'BSA-1A',type:'Regular'})
 await page.goto('/#/students')
 await page.getByRole('combobox',{name:'Department',exact:true}).selectOption('Business')
 await expect(page.getByRole('region',{name:'Student list',exact:true})).toContainText('Business Student')
 await expect(page.getByRole('region',{name:'Student list',exact:true})).toContainText('2027-1-0099')
 await expect(page.getByRole('region',{name:'Student list',exact:true})).toContainText('Year 1')
 await expect(page.getByRole('navigation',{name:'Student views'})).toHaveCount(0)
 const block=page.getByRole('button',{name:'Filter students in BSA-1A',exact:true})
 await expect(block).toContainText('1 registered student')
 await block.scrollIntoViewIfNeeded()
 await page.screenshot({path:info.outputPath('department-home-blocks.png'),animations:'disabled'})
 await block.click();await page.reload()
 await expect(page.getByRole('combobox',{name:'Department',exact:true})).toHaveValue('Business')
 await expect(page.getByRole('combobox',{name:'Block section',exact:true})).toHaveValue('BSA-1A')
 await expect(page.getByRole('region',{name:'Student list',exact:true})).toContainText('Business Student')
 await expect(block).toHaveAttribute('aria-pressed','true')
 expect(fixture.commands).toHaveLength(0)
})

for(const role of ['dean','associate_dean'])test(`${role} filters one complete directory by department, year, block and search across reloads`,async({page},info)=>{
 const fixture=await deanManagementUI(page,role)
 for(const student of fixture.records.directory.students as Record<string,unknown>[])student.department='Information Technology'
 for(let index=1;index<=40;index++)fixture.records.directory.students.push({id:`business-${index}`,student_number:`${index<=30?'2027':'2026'}-1-${String(index).padStart(4,'0')}`,name:`Business Learner ${index}`,surname:'Learner',first_name:`Business ${index}`,middle_name:'',email:`business${index}@example.invalid`,year_level:index<=30?1:2,department:'Business',program:'Bachelor of Science in Accountancy',status:'active',block:index<=20?'BSA-1A':index<=30?'BSA-1B':'BSA-2A',type:'Regular'})
 await page.goto('/#/students?tab=blocks')
 const table=page.getByRole('region',{name:'Student list',exact:true})
 await expect(page.getByRole('navigation',{name:'Student views'})).toHaveCount(0)
 await expect(page.getByRole('region',{name:'Department block sections'})).toHaveCount(0)
 await expect(table.getByRole('row')).toHaveCount(26)
 const pager=page.getByRole('navigation',{name:'students pages'})
 await pager.getByRole('button',{name:'Next',exact:true}).click()
 await page.reload();await expect(pager).toContainText('Page 2 of 2')
 await page.getByRole('combobox',{name:'Department',exact:true}).selectOption('Business')
 await expect(pager).toContainText('Page 1 of 2')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
 await page.screenshot({path:info.outputPath('department-directory.png'),animations:'disabled',fullPage:true})
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'Download CSV',exact:true}).click()
 const csv=await readFile((await (await download).path())!,'utf8')
 expect(csv).toContain('Business Learner 1');expect(csv).toContain('Business Learner 40');expect(csv).not.toContain('Riley Example')
 await expect(page.getByRole('button',{name:'Filter students in BSA-2A',exact:true})).toBeVisible()
 await page.getByRole('combobox',{name:'Year level',exact:true}).selectOption('1')
 await expect(page.getByRole('button',{name:'Filter students in BSA-2A',exact:true})).toHaveCount(0)
 await expect(page.getByRole('combobox',{name:'Block section',exact:true}).getByRole('option',{name:'BSA-2A',exact:true})).toHaveCount(0)
 const card=page.getByRole('button',{name:'Filter students in BSA-1B',exact:true})
 await card.focus();await card.press('Enter')
 await expect(page.getByRole('combobox',{name:'Block section',exact:true})).toHaveValue('BSA-1B')
 await expect(table.getByRole('row')).toHaveCount(11)
 await page.getByRole('searchbox',{name:'Search students',exact:true}).fill('Learner 25')
 await expect(table).toContainText('Business Learner 25')
 await expect(table.getByRole('row')).toHaveCount(2)
 await page.reload()
 await expect(page.getByRole('combobox',{name:'Department',exact:true})).toHaveValue('Business')
 await expect(page.getByRole('combobox',{name:'Year level',exact:true})).toHaveValue('1')
 await expect(page.getByRole('combobox',{name:'Block section',exact:true})).toHaveValue('BSA-1B')
 await expect(page.getByRole('searchbox',{name:'Search students',exact:true})).toHaveValue('Learner 25')
 await expect(table.getByRole('row')).toHaveCount(2)
 await table.scrollIntoViewIfNeeded();await page.screenshot({path:info.outputPath('unified-student-directory.png'),animations:'disabled'})
 await page.getByRole('combobox',{name:'Department',exact:true}).selectOption('Information Technology')
 await expect(page.getByRole('combobox',{name:'Block section',exact:true})).toHaveValue('')
 await expect(page.getByText('No student matches these filters.',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Clear filters',exact:true}).click()
 await expect(page.getByRole('combobox',{name:'Department',exact:true})).toHaveValue('')
 await expect(page.getByRole('button',{name:/Filter students in /})).toHaveCount(0)
 await expect(table.getByRole('row')).toHaveCount(26)
 expect(fixture.commands).toHaveLength(0)
})

