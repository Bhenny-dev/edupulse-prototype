import {test,expect} from '@playwright/test'
import {teachingLoadPdf,teachingLoadUI} from '../teaching-load-fixture'

for(const role of ['dean','associate_dean'])test(`${role} reviews a PDF, confirms a course-only assignment, imports once and filters its term`,async({page},info)=>{
 test.setTimeout(120000)
 await page.emulateMedia({reducedMotion:'reduce'})
 const fixture=await teachingLoadUI(page,role)
 await page.goto('/#/records')
 await page.locator('input[type=file][accept*=".pdf"]').setInputFiles({name:'approved-load.pdf',mimeType:'application/pdf',buffer:Buffer.from(await teachingLoadPdf())})
 const modal=page.getByRole('dialog',{name:'Review teaching loads',exact:true})
 await expect(modal).toBeVisible()
 await expect(modal).toContainText('IT 102 A — Programming foundations')
 await expect(modal.getByRole('button',{name:'Confirm selected loads'})).toBeDisabled()
 await expect(modal.getByLabel('Block section',{exact:true})).toHaveCount(0)
 await modal.getByRole('checkbox',{name:/I compared/}).check()
 await expect(modal.getByRole('button',{name:'Confirm selected loads'})).toBeEnabled()
 await expect(modal).toHaveCSS('opacity','1')
 await page.screenshot({path:`.data/course-load-intake/review-${info.project.name}-${role}.png`,fullPage:true,animations:'disabled'})
 await modal.getByRole('button',{name:'Confirm selected loads'}).click()
 await expect(modal).toContainText('Saved 1 selected loads')
 expect(fixture.commands).toHaveLength(1);expect(fixture.commands[0].entries[0]).toMatchObject({academic_year:'2026-2027',semester:'1st Semester',computed_hours:5,page:1})
 await modal.getByRole('button',{name:'Close',exact:true}).click()
 await expect(page.getByRole('button',{name:/IT 102.*loaded to/})).toBeVisible()
 await page.getByLabel('Academic term',{exact:true}).selectOption('2025-2026|2nd Semester')
 await expect(page.getByRole('button',{name:/IT 102.*not yet loaded/})).toHaveCount(0)
 await expect(page.getByRole('button',{name:'Add Course',exact:true})).toHaveCount(0)
 await page.reload();await expect(page.getByLabel('Academic term',{exact:true})).toHaveValue('2025-2026|2nd Semester')
 expect(fixture.commands).toHaveLength(1);expect(fixture.inference).toEqual([])
})

test('Pulse reads an image-only teaching-load table with OCR and offers a complete review without an AI request',async({page},info)=>{
 test.setTimeout(180000)
 await page.emulateMedia({reducedMotion:'reduce'})
 const fixture=await teachingLoadUI(page)
 await page.goto('/#/records')
 await page.getByRole('button',{name:'Open Pulse assistant'}).click()
 const pulse=page.getByRole('dialog',{name:'Pulse',exact:true})
 await pulse.locator('input[type=file]').setInputFiles({name:'scanned-load.pdf',mimeType:'application/pdf',buffer:Buffer.from(await teachingLoadPdf(true,page))})
 await expect(pulse.getByRole('button',{name:'Remove scanned-load.pdf',exact:true}).or(pulse.getByRole('alert')).first()).toBeVisible({timeout:120000})
 await expect(pulse.getByRole('alert')).toHaveCount(0)
 await expect(pulse.getByRole('button',{name:'Remove scanned-load.pdf',exact:true})).toBeVisible({timeout:120000})
 await expect(pulse).toContainText('teaching load, 1 class')
 await pulse.getByRole('textbox',{name:'Ask Pulse',exact:true}).fill('Extract the teaching loads')
 await pulse.getByRole('button',{name:'Send',exact:true}).click()
 await pulse.getByRole('button',{name:'Review extracted course loads'}).click()
 const modal=page.getByRole('dialog',{name:'Review teaching loads',exact:true})
 await expect(modal).toContainText('OCR was used')
 await expect(modal).toContainText(/IT\s*102\s*A/)
 await expect(modal.locator('.load-import-facts>div').filter({has:page.getByText('Computed hours / week',{exact:true})})).toContainText('5')
 await expect(modal.getByLabel('Block section',{exact:true})).toHaveCount(0)
 await expect(modal.getByRole('combobox',{name:'Course',exact:true})).toBeVisible()
 if(info.project.name==='mobile'){
  const dialogBox=await modal.boundingBox()
  expect(dialogBox!.height).toBeGreaterThanOrEqual(page.viewportSize()!.height-2)
 }
 await modal.getByRole('combobox',{name:'Course',exact:true}).scrollIntoViewIfNeeded()
 const box=await modal.getByRole('combobox',{name:'Course',exact:true}).boundingBox()
 expect(box!.y).toBeGreaterThanOrEqual(0);expect(box!.y+box!.height).toBeLessThanOrEqual(page.viewportSize()!.height)
 await page.screenshot({path:`.data/course-load-intake/ocr-${info.project.name}.png`,fullPage:false})
 expect(fixture.commands).toHaveLength(0);expect(fixture.inference).toEqual([])
 await modal.getByRole('button',{name:'Close',exact:true}).click()
 await expect(pulse).toBeVisible()
})

test('a subject missing from the recorded courses is added as a new course when the load is confirmed',async({page})=>{
 test.setTimeout(120000)
 const fixture=await teachingLoadUI(page)
 await page.goto('/#/records')
 await page.locator('input[type=file][accept*=".pdf"]').setInputFiles({name:'education-load.pdf',mimeType:'application/pdf',buffer:Buffer.from(await teachingLoadPdf(false,undefined,['PROF ED 16','Technology for Teaching and Learning 1']))})
 const modal=page.getByRole('dialog',{name:'Review teaching loads',exact:true})
 await expect(modal.getByRole('combobox',{name:'Course',exact:true})).toHaveValue('new:PROF ED 16')
 await expect(modal.getByRole('textbox',{name:'New course code',exact:true})).toHaveValue('PROF ED 16')
 await expect(modal).toContainText('PROF ED 16 is not in the recorded courses yet. Confirming adds it as “Technology for Teaching and Learning 1”, 3 units')
 await expect(modal).toContainText('1 selected · 1 new course will be added · ready to import')
 await modal.getByRole('checkbox',{name:/I compared/}).check()
 await modal.getByRole('button',{name:'Confirm selected loads'}).click()
 await expect(modal).toContainText('Saved 1 selected loads')
 expect(fixture.records.institutional!.some(r=>r.kind==='course_terms'&&r.data.CourseCode==='PROF ED 16'&&r.data.CourseTitle==='Technology for Teaching and Learning 1'&&r.data.Units==='3')).toBe(true)
 expect(fixture.commands).toHaveLength(1)
 expect(fixture.commands[0].entries[0]).toMatchObject({course_code:'PROF ED 16',course_title:'Technology for Teaching and Learning 1',semester:'1st Semester',academic_year:'2026-2027'})
 expect(fixture.commands[0].entries[0]).not.toHaveProperty('new_code')
})
