import { test, expect } from '@playwright/test'

test.beforeEach(async ({page})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'Instructor',exact:true}).click()
  await page.getByRole('button',{name:'Open Pulse assistant'}).click()
})
test('greetings answer locally under the interaction budget without model or retrieval calls',async({page},testInfo)=>{
  let heavy=0
  page.on('request',request=>{if(/action=(chat|operator|context|similarity|references)(?:&|$)/.test(request.url()))heavy++})
  await page.getByRole('textbox',{name:'Ask Pulse',exact:true}).fill('Hello')
  const elapsed=await page.evaluate(()=>new Promise<number>((resolve,reject)=>{
    const started=performance.now(),timeout=setTimeout(()=>{observer.disconnect();reject(new Error('No greeting appeared'))},2000)
    const observer=new MutationObserver(()=>{if([...document.querySelectorAll('.connected-pulse-text')].some(node=>node.textContent?.startsWith('Hi! What would you like'))){clearTimeout(timeout);observer.disconnect();resolve(performance.now()-started)}})
    observer.observe(document.body,{childList:true,subtree:true,characterData:true})
    ;(document.querySelector('button[aria-label="Send"]') as HTMLButtonElement).click()
  }))
  expect(heavy).toBe(0);expect(elapsed).toBeLessThan(150)
  await testInfo.attach('greeting-latency',{body:JSON.stringify({milliseconds:elapsed,heavyRequests:heavy}),contentType:'application/json'})
})
test('the office has named buddies, truthful achievements, accessible controls and real navigation handoff',async({page},testInfo)=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
  await page.getByRole('button', { name: 'Pulse options', exact: true }).click(); await page.getByRole('button',{name:'Open workspace buddies'}).click()
  const office=page.getByRole('dialog',{name:'Meet your crew.'})
  await expect(office).toBeVisible()
  await expect(office.locator('canvas')).toBeVisible({timeout:20000})
  // The office is the landing page's studio: the same room, with the six buddies as its crew.
  await expect(office.locator('.buddy-office-viewport[data-assembled]')).toBeVisible({timeout:60000})
  await expect(office.locator('.office-label')).toHaveCount(6)
  await office.getByRole('button',{name:/Talk to Ro,/}).click()
  await office.getByRole('button',{name:'Your role',exact:true}).click()
  await expect(office.getByRole('log')).toContainText('right row')
  await office.getByRole('button',{name:'Completed work',exact:true}).click()
  await expect(office.getByRole('log')).toContainText('haven’t recorded a completed task')
  await office.getByLabel('Message Ro').fill('Open my syllabus builder')
  await office.getByRole('button',{name:'Send to buddy'}).click()
  await expect(office.getByRole('status').filter({hasText:'Passing your request'})).toBeVisible()
  await expect(page).toHaveURL(/syllabus\?tab=builder/)
  await expect(office.getByRole('log')).toContainText('tool card in Pulse')
  await office.getByRole('button',{name:'Pause office animation'}).click()
  await expect(office.getByRole('button',{name:'Resume office animation'})).toHaveAttribute('aria-pressed','true')
  if(testInfo.project.name==='desktop')await office.screenshot({path:'.data/office-review-desktop.png'})
  else await page.screenshot({path:'.data/office-review-mobile.png'})
  await page.keyboard.press('Escape')
  await expect(office).toHaveCount(0)
  expect(errors).toEqual([])
})
test('reduced motion is respected and office loading does not block a simple edit',async({page})=>{
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.getByRole('button', { name: 'Pulse options', exact: true }).click(); await page.getByRole('button',{name:'Open workspace buddies'}).click()
  const office=page.getByRole('dialog',{name:'Meet your crew.'})
  await expect(office).toContainText('Reduced motion is on.')
  await office.getByRole('button',{name:'Close workspace'}).click()
  await page.goto('/#/syllabus?tab=builder')
  await page.getByLabel('Course',{exact:true}).selectOption('IT 102')
  const outcome=page.getByPlaceholder('Program outcome 1',{exact:true})
  await outcome.fill('Understand variables in programs')
  if(await page.getByRole('button',{name:'Open Pulse assistant'}).count()) await page.getByRole('button',{name:'Open Pulse assistant'}).click()
  let model=0;page.on('request',request=>{if(request.url().includes('action=operator'))model++})
  await page.getByRole('textbox',{name:'Ask Pulse',exact:true}).fill('Replace "Understand" with "Explain" in the program outcomes')
  await page.getByRole('button',{name:'Send',exact:true}).click()
  const preview=page.getByRole('region',{name:'Review content edit'})
  await expect(preview).toContainText('Explain variables in programs')
  await expect(outcome).toHaveValue('Understand variables in programs')
  expect(model).toBe(0)
})
