import { test, expect } from '../snapshots/fixtures'
import { workspaceRecoveryUI, causeWorkspaceSaveFailure, pendingExplanation } from '../workspace-recovery-fixture'

test('save failures leave pages clear and can be backed up and retried from Settings', async ({ page }) => {
  const fixture = await workspaceRecoveryUI(page)
  await causeWorkspaceSaveFailure(page)
  await expect(page.getByTestId('workspace-save-state')).toContainText('Cloud save failed')
  await expect(page.locator('.workspace-status')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Retry save', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Export backup', exact: true })).toHaveCount(0)
  await expect(page.getByRole('alert').filter({ hasText: 'Cloud save failed' })).toHaveCount(0)
  await page.goto('/#/settings?tab=privacy')
  const recovery = page.getByRole('region', { name: 'Workspace save recovery', exact: true })
  await expect(recovery.getByRole('alert')).toContainText('Cloud save failed')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export workspace backup', exact: true }).click()
  const file = await (await download).path()
  const saved = JSON.parse(await (await import('node:fs/promises')).readFile(file!, 'utf8'))
  expect(saved.content['baseline-quiz'].content.questions[0].explanation).toBe(pendingExplanation)
  fixture.allowSave()
  await recovery.getByRole('button', { name: 'Retry save', exact: true }).click()
  await expect(page.getByTestId('workspace-save-state')).toHaveText('Saved')
  await expect(recovery).toHaveCount(0)
  expect(fixture.getSavedWorkspace().content['baseline-quiz'].content.questions[0].explanation).toBe(pendingExplanation)
})

test('Settings requires a backup before resolving a workspace conflict', async ({ page }) => {
  await workspaceRecoveryUI(page, true)
  await causeWorkspaceSaveFailure(page)
  await expect(page.getByTestId('workspace-save-state')).toContainText('newer workspace')
  await expect(page.locator('.workspace-status')).toHaveCount(0)
  await page.goto('/#/settings?tab=privacy')
  const latest = page.getByRole('button', { name: 'Load latest after export', exact: true })
  await expect(latest).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Retry save', exact: true })).toHaveCount(0)
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export workspace backup', exact: true }).click()
  await download
  await expect(latest).toBeEnabled()
  await latest.click()
  await expect(page.getByTestId('workspace-save-state')).toHaveText('Saved')
  await expect(page.getByRole('region', { name: 'Workspace save recovery', exact: true })).toHaveCount(0)
  await page.goto('/#/courseware?course=baseline-syllabus&week=1')
  await page.locator('[data-content-id="baseline-quiz"]').getByRole('button', { name: 'View', exact: true }).click()
  await expect(page.getByLabel('Question 1 explanation', { exact: true })).toHaveValue('Reviewed course reference.')
})
