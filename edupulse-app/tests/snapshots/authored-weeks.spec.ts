import {test,expect} from './fixtures'
import {authoredWeeksUI} from '../authored-weeks-fixture'
const folder='../feature-documentation/system-manual/39-authored-weeks'
test('authored Java packs remain drafts and disclose direct authoring and instructor marking',async({page})=>{
 const f=await authoredWeeksUI(page)
 await page.goto('/#/courseware?course=authored-java&week=3')
 await expect(page.locator('[data-week="3"] [data-content-id]')).toHaveCount(3)
 await expect(page.locator('[data-week="3"] [data-content-id] .badge')).toHaveText(['Draft','Draft','Draft'])
 await page.screenshot({path:`${folder}/01-weekly-drafts.png`,animations:'disabled'})
 await page.locator('[data-content-id="gen-mat-authored-java-w3"]').getByRole('button',{name:'View',exact:true}).click()
 await expect(page.getByText('Context and principle',{exact:true})).toBeVisible()
 await expect(page.locator('.doc-viewer-text').first()).toContainText('String')
 await page.evaluate(()=>window.scrollTo(0,0))
 await page.screenshot({path:`${folder}/02-java-lesson.png`,animations:'disabled'})
 await page.locator('.ai-draft-evidence').scrollIntoViewIfNeeded()
 await expect(page.getByText(/Authored directly in the coding session/)).toBeVisible()
 await page.screenshot({path:`${folder}/03-review-disclosure.png`,animations:'disabled'})
 await page.reload();await expect(page.locator('.doc-viewer-text').first()).toContainText('String')
 await page.getByRole('button',{name:'Back',exact:true}).click()
 await page.locator('[data-content-id="gen-assess-authored-java-w3"]').getByRole('button',{name:'View',exact:true}).click()
 await expect(page.getByText(/Open-book written assessment/)).toBeVisible()
 await page.evaluate(()=>window.scrollTo(0,0))
 await page.screenshot({path:`${folder}/04-written-assessment.png`,animations:'disabled'})
 expect(f.records.attempts).toHaveLength(0);expect(f.records.accesses).toHaveLength(0)
})
