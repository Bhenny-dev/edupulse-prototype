import { test, expect } from './fixtures'
import { instructorCourseUI } from '../instructor-course-fixture'
test('assigned instructor course topics on a phone', async ({ page }) => {
  const fixture = await instructorCourseUI(page)
  await page.goto('/#/syllabus?tab=mine')
  await expect(page.getByRole('navigation', { name: 'Syllabus sections' })).toBeVisible()
  await page.getByRole('button', { name: 'Open menu', exact: true }).click()
  await expect(page.getByRole('navigation', { name: 'Mobile navigation' }).getByRole('link', { name: 'Syllabus', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Close menu', exact: true }).click()
  await page.goto(`/#/courseware?course=${fixture.syllabus.id}`)
  await expect(page.getByRole('navigation',{name:'Course workspace views'}).getByRole('button')).toHaveText(['Weeks and topics','Block sections'])
  await page.locator('[data-topic="variables"] > summary').click()
  await expect(page.getByRole('button', { name: 'Add overall assessment', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: '../feature-documentation/system-manual/44-instructor-course-workspace/07-mobile-course.png', animations: 'disabled' })
  await page.locator('.instructor-sequence-item').filter({has:page.getByText('Variables lesson',{exact:true})}).getByRole('button',{name:'Open',exact:true}).click()
  const reader=page.getByRole('dialog',{name:'Variables lesson',exact:true})
  await expect(reader).toHaveClass(/page-modal/)
  await reader.screenshot({path:'../feature-documentation/system-manual/44-instructor-course-workspace/12-mobile-page-reader.png',animations:'disabled'})
  await page.keyboard.press('Escape')
  await page.getByRole('button',{name:'Block sections',exact:true}).click()
  await page.getByRole('button',{name:'Schedule BSIT-1A'}).click()
  await expect(page.getByRole('dialog',{name:'Delivery schedule for BSIT-1A'})).toBeVisible()
  await page.screenshot({path:'../feature-documentation/system-manual/44-instructor-course-workspace/10-mobile-block-schedule.png',animations:'disabled'})
})
