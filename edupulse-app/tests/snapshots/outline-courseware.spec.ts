import {test,expect} from './fixtures'
import {outlineCoursewareUI} from '../outline-courseware-fixture'
const folder='../feature-documentation/system-manual/26-outline-driven-courseware'
test('substantive outline lesson, planned discussion and final review remain in the existing workspace',async({page})=>{
  const fixture=await outlineCoursewareUI(page);await page.goto(`/#/courseware?course=${fixture.syllabus.id}&week=5`)
  await page.getByRole('button',{name:'Week 5 actions',exact:true}).click();await page.getByRole('menuitem',{name:'Regenerate week',exact:true}).click()
  await expect(page.getByText('Week 5: 2 AI drafts saved for review.',{exact:true})).toBeVisible()
  await expect(page.getByText('Week 5: 2 AI drafts saved for review.',{exact:true})).toHaveCount(0,{timeout:10000})
  await page.screenshot({path:`${folder}/01-planned-items.png`,animations:'disabled'})
  await page.locator(`[data-content-id="${fixture.id}"]`).getByRole('button',{name:'View',exact:true}).click()
  await expect(page.getByText('State, conditions and loop counters',{exact:true}).first()).toBeVisible();await page.screenshot({path:`${folder}/02-lesson-context.png`,animations:'disabled'})
  await page.getByText('Worked nested trace',{exact:true}).scrollIntoViewIfNeeded();await page.screenshot({path:`${folder}/03-worked-example.png`,animations:'disabled'})
  await page.locator('.ai-draft-evidence').scrollIntoViewIfNeeded();await page.screenshot({path:`${folder}/04-final-review.png`,animations:'disabled'})
  await page.getByRole('button',{name:'Back',exact:true}).click()
  await page.locator(`[data-content-id="gen-act-${fixture.syllabus.id}-w5"]`).getByRole('button',{name:'View',exact:true}).click()
  await expect(page.getByText('Discussion tasks',{exact:true})).toBeVisible();await page.screenshot({path:`${folder}/05-discussion-guide.png`,animations:'disabled'})
})

test('saved parts remain visible after failure and reload, then resume without replaying completed inference',async({page})=>{
  const fixture=await outlineCoursewareUI(page);fixture.failStep('lesson-3')
  await page.goto(`/#/courseware?course=${fixture.syllabus.id}&week=5`)
  await page.getByRole('button',{name:'Week 5 actions',exact:true}).click();await page.getByRole('menuitem',{name:'Regenerate week',exact:true}).click()
  await expect(page.getByText('Generation did not finish',{exact:true})).toBeVisible()
  await page.screenshot({path:`${folder}/06-saved-parts.png`,animations:'disabled'})
  await page.reload();await expect(page.getByRole('button',{name:'Resume',exact:true})).toBeVisible()
  await page.screenshot({path:`${folder}/07-resume-after-reload.png`,animations:'disabled'})
  await page.locator('[data-content-id="generation-outline-plan-syllabus-w5"]').getByRole('button',{name:'View',exact:true}).click()
  await expect(page.getByRole('button',{name:'Edit',exact:true})).toHaveCount(0)
  await page.screenshot({path:`${folder}/08-unfinished-reader.png`,animations:'disabled'})
  await page.getByRole('button',{name:'Back',exact:true}).click()
  await page.getByRole('button',{name:'Back to courses',exact:true}).click()
  await expect(page.getByText('1 unfinished week',{exact:true})).toBeVisible()
  await page.screenshot({path:`${folder}/12-course-list-progress.png`,animations:'disabled'})
  await page.evaluate(()=>localStorage.setItem('edupulse-dark-mode','true'))
  await page.goto(`/#/courseware?course=${fixture.syllabus.id}&week=5`);await page.reload()
  await expect(page.getByRole('button',{name:'Resume',exact:true})).toBeVisible()
  await page.screenshot({path:`${folder}/11-dark-resume.png`,animations:'disabled'})
})

test('validated progress is visible while the next part is still generating',async({page})=>{
  const fixture=await outlineCoursewareUI(page);fixture.holdStep('lesson-2')
  await page.goto(`/#/courseware?course=${fixture.syllabus.id}&week=5`)
  await page.getByRole('button',{name:'Week 5 actions',exact:true}).click();await page.getByRole('menuitem',{name:'Regenerate week',exact:true}).click()
  await expect(page.getByText('Week 5: unfinished draft (1/6 parts)',{exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'Stop generation',exact:true})).toBeVisible()
  await page.screenshot({path:`${folder}/10-incremental-progress.png`,animations:'disabled'})
  await page.getByRole('button',{name:'Stop generation',exact:true}).click();fixture.releaseStep()
  await expect(page.getByRole('button',{name:'Resume',exact:true})).toBeEnabled()
})
