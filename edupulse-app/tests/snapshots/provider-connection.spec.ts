import { test, expect } from './fixtures.js'
import { mkdir } from 'node:fs/promises'
import { providerFixture } from '../browser/provider-fixture.js'

test('provider connection: clearly saved credential, synchronized status and recoverable replacement', async ({ page }) => {
  const fixture = await providerFixture(page)
  await page.goto('/')
  await page.getByRole('button', { name: 'Instructor', exact: true }).click()
  await page.goto('/#/settings?tab=ai-provider')
  await page.getByLabel('AI provider', { exact: true }).selectOption('openai')
  await page.getByLabel('Provider API key', { exact: true }).fill('synthetic-provider-key-for-ui')
  await page.getByRole('button', { name: 'Connect and load models', exact: true }).click()
  await expect(page.locator('[data-pulse-target="AI pipeline status"]')).toContainText('Generation has not been tested.')
  await expect(page.getByLabel('Saved provider credential')).toBeVisible()
  await mkdir('../feature-documentation/system-manual/08-ai-connections', { recursive: true })
  await page.locator('[data-pulse-target="AI connection"]').screenshot({ path: '../feature-documentation/system-manual/08-ai-connections/04-saved-provider-credential.png', animations: 'disabled', style: '.app-topbar{position:static !important}' })
  await page.getByRole('button', { name: 'Test selected model', exact: true }).click()
  await expect(page.locator('[data-pulse-target="AI pipeline status"]')).toContainText('Generation verified')
  await page.locator('[data-pulse-target="AI connection"]').screenshot({ path: '../feature-documentation/system-manual/08-ai-connections/06-generation-verified.png', animations: 'disabled', style: '.app-topbar{position:static !important}' })
  fixture.failNextTest()
  await page.getByRole('button', { name: 'Test selected model', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('unavailable for this account')
  await page.locator('[data-pulse-target="AI connection"]').screenshot({ path: '../feature-documentation/system-manual/08-ai-connections/07-model-access-error.png', animations: 'disabled', style: '.app-topbar{position:static !important}' })
  await page.getByRole('button', { name: 'Replace API key', exact: true }).click()
  await page.getByLabel('Provider API key', { exact: true }).fill('synthetic-rejected-key')
  await page.getByRole('button', { name: 'Connect and load models', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('rejected')
  await page.locator('[data-pulse-target="AI connection"]').screenshot({ path: '../feature-documentation/system-manual/08-ai-connections/05-provider-replacement-error.png', animations: 'disabled', style: '.app-topbar{position:static !important}' })
})

test('failed authorization remains visible when no previous provider is connected', async ({ page }) => {
  await providerFixture(page)
  await page.route('**/api/ai?action=provider-oauth', route => route.fulfill({ status: 400, json: { error: { code: 'OAUTH_EXCHANGE_FAILED', message: 'Authorization could not finish. Start Connect with OpenRouter again.' } } }))
  await page.goto('/')
  await page.getByRole('button', { name: 'Instructor', exact: true }).click()
  await page.goto('/auth/provider/openrouter?code=synthetic-code&state=synthetic-callback-state-12345678901234567890')
  await expect(page.getByRole('alert')).toContainText('Authorization could not finish')
  await page.locator('[data-pulse-target="AI connection"]').screenshot({ path: '../feature-documentation/system-manual/08-ai-connections/10-authorization-error.png', animations: 'disabled', style: '.app-topbar{position:static !important}' })
})

test('OpenRouter callback retains an authorized credential during a catalog outage and recovers on refresh', async ({ page }) => {
  const fixture = await providerFixture(page)
  await page.route('**/api/ai?action=provider-oauth', route => route.fulfill({ json: fixture.authorize('openrouter', true) }))
  await page.goto('/')
  await page.getByRole('button', { name: 'Instructor', exact: true }).click()
  await page.goto('/auth/provider/openrouter?code=synthetic-code&state=synthetic-callback-state-12345678901234567890')
  await expect(page.getByLabel('Saved provider credential')).toBeVisible()
  await expect(page.getByRole('alert')).toContainText('no need to authorize again')
  await page.locator('[data-pulse-target="AI connection"]').screenshot({ path: '../feature-documentation/system-manual/08-ai-connections/08-openrouter-catalog-retry.png', animations: 'disabled', style: '.app-topbar{position:static !important}' })
  await page.getByRole('button', { name: 'Refresh models', exact: true }).click()
  await expect(page.getByLabel('Available model')).toHaveValue('gpt-4.1-mini')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.locator('[data-pulse-target="AI connection"]').screenshot({ path: '../feature-documentation/system-manual/08-ai-connections/09-mobile-provider-connection.png', animations: 'disabled', style: '.app-topbar{position:static !important}.connected-pulse-dock{visibility:hidden !important}' })
})
